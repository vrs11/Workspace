import { test } from "node:test";
import assert from "node:assert/strict";
import {
  mkdtempSync,
  mkdirSync,
  readFileSync,
  writeFileSync,
  copyFileSync,
  rmSync,
  existsSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { join, dirname } from "node:path";
import { spawn } from "node:child_process";
import process from "node:process";

function fixture() {
  const root = mkdtempSync(join(tmpdir(), "workspace-license-cache-"));
  for (const path of [
    "package.json",
    "pnpm-lock.yaml",
    "src-tauri/Cargo.toml",
    "src-tauri/Cargo.lock",
    "patches/manifest.json",
    "scripts/license-overrides.json",
  ]) {
    mkdirSync(dirname(join(root, path)), { recursive: true });
    writeFileSync(
      join(root, path),
      path === "package.json" ? '{"type":"module"}' : "fixture",
    );
  }
  copyFileSync("rust-toolchain.toml", join(root, "rust-toolchain.toml"));
  copyFileSync(
    "scripts/prepare-licenses.mjs",
    join(root, "scripts/prepare-licenses.mjs"),
  );
  writeFileSync(
    join(root, "scripts/licenses.mjs"),
    `
    import {mkdirSync,writeFileSync,readFileSync,existsSync} from 'node:fs';
    import {join} from 'node:path';
    const output=process.env.AW_LICENSE_OUTPUT_DIR;
    mkdirSync(output,{recursive:true});
    writeFileSync(join(output,'notice.txt'),'complete licensed bytes');
    if(process.env.LICENSE_FIXTURE_FAIL)process.exit(17);
    await new Promise(resolve=>setTimeout(resolve,100));
    const count=existsSync('generations')?Number(readFileSync('generations','utf8')):0;
    writeFileSync('generations',String(count+1));
  `,
  );
  const run = (args = [], extraEnv = {}) =>
    new Promise((resolve, reject) => {
      const child = spawn(
        process.execPath,
        ["scripts/prepare-licenses.mjs", ...args],
        {
          cwd: root,
          env: { ...process.env, ...extraEnv },
          stdio: ["ignore", "pipe", "pipe"],
        },
      );
      let output = "";
      child.stdout.on("data", (chunk) => (output += chunk));
      child.stderr.on("data", (chunk) => (output += chunk));
      child.on("error", reject);
      child.on("close", (code) => resolve({ code, output }));
    });
  return {
    root,
    run,
    count: () => Number(readFileSync(join(root, "generations"), "utf8")),
    dispose: () => rmSync(root, { recursive: true, force: true }),
  };
}
test("legal resources reuse a verified cache and rebuild when inputs or generated bytes change", async () => {
  const f = fixture();
  try {
    assert.equal((await f.run()).code, 0);
    assert.equal((await f.run()).code, 0);
    assert.equal(f.count(), 1);
    writeFileSync(join(f.root, "pnpm-lock.yaml"), "changed dependency lock");
    assert.equal((await f.run()).code, 0);
    assert.equal(f.count(), 2);
    writeFileSync(
      join(f.root, "artifacts/legal/notice.txt"),
      "partial or altered output",
    );
    assert.equal((await f.run()).code, 0);
    assert.equal(f.count(), 3);
    assert.equal(
      readFileSync(join(f.root, "artifacts/legal/notice.txt"), "utf8"),
      "complete licensed bytes",
    );
  } finally {
    f.dispose();
  }
});
test("concurrent builds publish one complete legal-resource snapshot", async () => {
  const f = fixture();
  try {
    const results = await Promise.all([f.run(), f.run(), f.run()]);
    for (const result of results) assert.equal(result.code, 0, result.output);
    assert.equal(f.count(), 1);
    assert.ok(existsSync(join(f.root, "artifacts/legal/cache.json")));
    assert.equal(existsSync(join(f.root, "artifacts/.licenses.lock")), false);
  } finally {
    f.dispose();
  }
});
test("failed license generation preserves the last complete resources and allows retry", async () => {
  const f = fixture();
  try {
    assert.equal((await f.run()).code, 0);
    const before = readFileSync(
      join(f.root, "artifacts/legal/cache.json"),
      "utf8",
    );
    assert.notEqual(
      (await f.run(["--force"], { LICENSE_FIXTURE_FAIL: "1" })).code,
      0,
    );
    assert.equal(
      readFileSync(join(f.root, "artifacts/legal/cache.json"), "utf8"),
      before,
    );
    assert.equal(
      readFileSync(join(f.root, "artifacts/legal/notice.txt"), "utf8"),
      "complete licensed bytes",
    );
    assert.equal(existsSync(join(f.root, "artifacts/.licenses.lock")), false);
    assert.equal((await f.run(["--force"])).code, 0);
    assert.equal(f.count(), 2);
  } finally {
    f.dispose();
  }
});
