#[test]
fn application_dto_drift() {
    let path =
        std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("../src/generated/protocol.ts");
    let expected = String::from("// Generated by ts-rs from Rust DTOs. Do not edit.\n")
        + &agent_workspace::dto::export_types();
    if std::env::var_os("UPDATE_GENERATED").is_some() {
        std::fs::create_dir_all(path.parent().unwrap()).unwrap();
        std::fs::write(&path, &expected).unwrap();
    }
    assert_eq!(
        std::fs::read_to_string(path)
            .expect("Generate with UPDATE_GENERATED=1 cargo test --test generated"),
        expected
    );
}
